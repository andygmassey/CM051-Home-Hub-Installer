#!/usr/bin/env python3
"""Generate vendor/cm041/assistant_api/sensitive_topics.py FROM the one list,
vendor/cm059_editor/compiler/sensitive_topics.py (board row 2471).

The Assistant API (ical-server) is installed as its own directory, apart from
the Editor, so it cannot import the Editor's module at run time. It gets a
GENERATED copy instead: a fixed header plus the source bytes, never a second
hand-written list. Edit the source, then run this; --check exits 1 when the
copy is stale (tests/test_api_preferences_never_returns_a_special_category_topic.py
runs it).

    python3 scripts/gen_assistant_api_sensitive_topics.py [--check]
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "vendor", "cm059_editor", "compiler", "sensitive_topics.py")
DST = os.path.join(ROOT, "vendor", "cm041", "assistant_api", "sensitive_topics.py")
HEADER = (
    "# GENERATED by scripts/gen_assistant_api_sensitive_topics.py from\n"
    "# vendor/cm059_editor/compiler/sensitive_topics.py. DO NOT EDIT: edit the\n"
    "# source and re-run the generator. A stale copy fails CI.\n"
)


def expected() -> str:
    with open(SRC, encoding="utf-8") as fh:
        return HEADER + fh.read()


def main(argv) -> int:
    want = expected()
    if "--check" in argv:
        try:
            with open(DST, encoding="utf-8") as fh:
                have = fh.read()
        except OSError as exc:
            print("STALE: {} unreadable ({})".format(DST, exc))
            return 1
        if have != want:
            print("STALE: {} differs from the generator output; re-run it".format(DST))
            return 1
        print("CURRENT: assistant_api/sensitive_topics.py == generated from the one list")
        return 0
    with open(DST, "w", encoding="utf-8") as fh:
        fh.write(want)
    print("wrote {}".format(DST))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
